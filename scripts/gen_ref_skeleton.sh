#!/usr/bin/env bash
# Generates the skeleton files of the reference pedalboard work packages
# (spec/reference-pedalboard/specs/IMPLEMENTATION_PLAN.md sec 2 rule S-1 and sec 4).
#
# Every stub starts with "// OWNER: WPn" and compiles on its own (header guard +
# empty namespace, or a trivial body), so the globbed CMake, the includes and the
# registry work from day one and no two agents ever create the same path.
# Ownership then transfers: a work package fills the bodies of ITS files and never
# edits another package's file (file an errata request instead).
#
# The script NEVER overwrites an existing file, so it is safe to re-run; keep it
# committed. Hand-written interface headers and interim implementations of WP1
# (IPedal.h, Board.h, MidiRouter.cpp, ...) are not in the manifest.
#
#   scripts/gen_ref_skeleton.sh            create the files that are missing
#   scripts/gen_ref_skeleton.sh --check    list missing files, exit 1 if any
#
# Manifest line: <owner> <kind> <path> [function]
#   h <path>        header with #pragma once and the directory's namespace
#   cpp <path>      translation unit that includes its sibling header when one exists
#   hcpp <base>     <base>.h and <base>.cpp
#   face <path>     UI face stub (includes PedalFaceFactory.h)
#   test <path>     test file stub (includes TestFramework.h)
#   inc <path>      data include
#   reg <path> <fn> registration function stub (Registration.h)
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
mode="create"
[[ "${1:-}" == "--check" ]] && mode="check"

RP="Source/ReferencePedals"
UI="Source/UI/ReferencePedals"
T="Source/Tests"

namespace_for() {
    case "$1" in
        $RP/Generic/*)  echo "luthier::reference::generic" ;;
        $RP/Models/*)   echo "luthier::reference::models" ;;
        $RP/Midi/*)     echo "luthier::reference::midi" ;;
        $RP/Routing/*)  echo "luthier::reference::routing" ;;
        $RP/Common/*)   echo "luthier::reference::common" ;;
        *)              echo "luthier::reference" ;;
    esac
}

missing=0
created=0

emit() { # owner kind path [fn]
    local owner="$1" kind="$2" path="$3" fn="${4:-}"
    local file="$root/$path"
    if [[ -e "$file" ]]; then return 0; fi
    if [[ "$mode" == "check" ]]; then echo "missing: $path"; missing=$((missing + 1)); return 0; fi
    mkdir -p "$(dirname "$file")"
    local ns; ns="$(namespace_for "$path")"
    local base; base="$(basename "$path")"
    {
        echo "// OWNER: $owner"
        case "$kind" in
            h)
                echo "// Skeleton generated by scripts/gen_ref_skeleton.sh: $owner fills this header."
                echo "#pragma once"
                echo
                echo "namespace $ns"
                echo "{"
                echo "} // namespace $ns"
                ;;
            cpp|face)
                echo "// Skeleton generated by scripts/gen_ref_skeleton.sh: $owner fills this file."
                local hdr="${base%.cpp}.h"
                if [[ "$kind" == "face" ]]; then
                    echo '#include "../PedalFaceFactory.h"'
                elif [[ -e "$(dirname "$file")/$hdr" ]]; then
                    echo "#include \"$hdr\""
                fi
                echo
                echo "namespace $ns"
                echo "{"
                echo "} // namespace $ns"
                ;;
            reg)
                echo "// Skeleton generated by scripts/gen_ref_skeleton.sh: $owner registers its models here"
                echo "// with PedalRegistry::add(desc, factory). The function name and its place in"
                echo "// PedalRegistry::registerAll() are frozen (Registration.h)."
                echo '#include "../Registration.h"'
                echo '#include "../PedalRegistry.h"'
                echo
                echo "namespace luthier::reference"
                echo "{"
                echo
                echo "void $fn() {}"
                echo
                echo "} // namespace luthier::reference"
                ;;
            test)
                echo "// Skeleton generated by scripts/gen_ref_skeleton.sh: $owner adds its LUTHIER_TEST cases here."
                echo "// Suite names start with RefPedal so 'LuthierTests refpedal' selects them (plan sec 1, E24)."
                echo '#include "TestFramework.h"'
                ;;
            inc)
                echo "// Skeleton generated by scripts/gen_ref_skeleton.sh: $owner supplies the data."
                ;;
        esac
    } > "$file"
    created=$((created + 1))
}

hcpp() { emit "$1" h "$2.h"; emit "$1" cpp "$2.cpp"; }

