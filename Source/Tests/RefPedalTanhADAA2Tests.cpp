LUTHIER_TEST(RefPedalTanhADAA2, highPrecisionRepeatedAndSeparatedNodes)
{
    double worst = 0;
    for (auto c : cases)
    {
        TanhADAA2 q;
        q.prepareFactor(1);
        q.process(c.c);
        q.process(c.b);
        double y = q.process(c.a);
        worst = std::max(worst, std::abs(y - c.expected));
        CHECK_NEAR(y, c.expected, 2e-10);
    }
    CHECK(worst < 2e-10);
}
LUTHIER_TEST(RefPedalTanhADAA2, exactPaddingAndLinearLimit)
{
    for (int factor : {1, 2, 4, 8})
    {
        TanhADAA2 q;
        q.prepareFactor(factor);
        CHECK(q.latencyHighRateSamples() == factor);
        CHECK(q.latencyBaseSamples() == 1);
        double sum = 0, moment = 0;
        for (int i = 0; i < 32; ++i)
        {
            double y = q.process(i == 0 ? 1e-8 : 0) / 1e-8;
            sum += y;
            moment += i * y;
            const double expected = i >= factor - 1 && i <= factor + 1 ? 1.0 / 3 : 0;
            CHECK_NEAR(y, expected, 1e-12);
        }
        CHECK_NEAR(sum, 1, 1e-12);
        CHECK_NEAR(moment, factor, 1e-12);
    }
    // No claim of a pure delay: the exact linear limit is a three-tap average.
    TanhADAA2 q;
    q.prepareFactor(1);
    double old = 0, older = 0;
    for (int i = 0; i < 1024; ++i)
    {
        double x = 1e-8 * std::sin(i * .713);
        CHECK_NEAR(q.process(x), (x + old + older) / 3, 1e-20);
        older = old;
        old = x;
    }
}
LUTHIER_TEST(RefPedalTanhADAA2, gainAutomationFiniteBoundAndSilence)
{
    TanhADAA2 q;
    q.prepareFactor(8);
    for (int i = 0; i < 32; ++i)
        CHECK(q.process(0) == 0);
    for (int i = 0; i < 100000; ++i)
    {
        double gain = i < 50000 ? std::exp(i * .0002) : (i % 2 ? 1e6 : 1e-6);
        double y = q.process(gain * std::sin(i * .317));
        CHECK(std::isfinite(y));
        CHECK(std::abs(y) <= 1);
    }
    for (double v : {std::numeric_limits<double>::quiet_NaN(), std::numeric_limits<double>::infinity(),
                     -std::numeric_limits<double>::infinity(), 1e-310})
        CHECK(std::isfinite(q.process(v)));
    q.reset();
    for (int i = 0; i < 32; ++i)
        CHECK(q.process(0) == 0);
}
